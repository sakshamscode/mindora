/**
 * Retrieve current user UI language
 */
export async function getLanguage() {
  if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
    const res = await chrome.storage.local.get(['mindora_language']);
    if (res.mindora_language) return res.mindora_language;
  }
  if (typeof localStorage !== 'undefined') {
    const local = localStorage.getItem('mindora_language');
    if (local) return local;
  }
  return 'en';
}

/**
 * Set user UI language
 */
export async function setLanguage(langCode) {
  if (!DICTIONARY[langCode]) langCode = 'en';
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('mindora_language', langCode);
  }
  if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
    await chrome.storage.local.set({ mindora_language: langCode });
  }
  return langCode;
}

/**
 * Lookup translated string
 */
export function t(key, lang = 'en', params = {}) {
  const dict = DICTIONARY[lang] || DICTIONARY.en;
  let text = dict[key] || DICTIONARY.en[key] || key;
  for (const [paramKey, paramVal] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), paramVal);
  }
  return text;
}

/**
 * Walk DOM element and translate elements with data-i18n attributes
 */
export function applyTranslations(root = document, lang = 'en') {
  const elements = root.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      el.textContent = t(key, lang);
    }
  });

  const placeholders = root.querySelectorAll('[data-i18n-placeholder]');
  placeholders.forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) {
      el.setAttribute('placeholder', t(key, lang));
    }
  });

  const titles = root.querySelectorAll('[data-i18n-title]');
  titles.forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) {
      el.setAttribute('title', t(key, lang));
    }
  });

  // Set document text direction if RTL (e.g. Arabic)
  const langMeta = SUPPORTED_LANGUAGES.find(l => l.code === lang);
  if (langMeta && langMeta.dir) {
    document.documentElement.setAttribute('dir', langMeta.dir);
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
  }
}
